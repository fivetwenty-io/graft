// Command gengrapheme writes grapheme_table.go, the table of grapheme
// cluster break properties that the Oniguruma flavor's \X, \y, and \Y
// read. It merges the Grapheme_Cluster_Break values of
// GraphemeBreakProperty.txt with the Extended_Pictographic code points of
// emoji-data.txt, which no Grapheme_Cluster_Break value covers.
//
// The table follows Unicode 16.0.0 rather than the Unicode version of the
// Go toolchain, because the flavor answers as jq 1.8.2 does, and jq 1.8.2
// vendors Oniguruma 6.9.10, whose grapheme tables are Unicode 16.0.0.
//
//	go generate ./pkg/regex
//	go run ./internal/gengrapheme -break GraphemeBreakProperty.txt -emoji emoji-data.txt
package main

import (
	"bufio"
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

// unicodeVersion is the Unicode version of the data the table is built
// from, the version of Oniguruma 6.9.10's grapheme tables.
const unicodeVersion = "16.0.0"

// emojiVersion is the emoji-data.txt version that ships with
// unicodeVersion.
const emojiVersion = "16.0"

// props maps each property the table records to the constant that names it
// in package regex.
var props = map[string]string{
	"CR":                    "gbCR",
	"LF":                    "gbLF",
	"Control":               "gbControl",
	"Extend":                "gbExtend",
	"ZWJ":                   "gbZWJ",
	"Regional_Indicator":    "gbRegionalIndicator",
	"Prepend":               "gbPrepend",
	"SpacingMark":           "gbSpacingMark",
	"L":                     "gbL",
	"V":                     "gbV",
	"T":                     "gbT",
	"LV":                    "gbLV",
	"LVT":                   "gbLVT",
	"Extended_Pictographic": "gbPictographic",
}

// span is one line of a data file, a range of code points and a property.
type span struct {
	lo, hi rune
	prop   string
}

func main() {
	breaks := flag.String("break", "", "path to GraphemeBreakProperty.txt; downloaded from unicode.org when empty")
	emoji := flag.String("emoji", "", "path to emoji-data.txt; downloaded from unicode.org when empty")
	out := flag.String("o", "grapheme_table.go", "output file")
	flag.Parse()

	spans, err := read(*breaks, "auxiliary/GraphemeBreakProperty.txt", "# GraphemeBreakProperty-"+unicodeVersion+".txt", "")
	if err != nil {
		log.Fatal(err)
	}
	pictographic, err := read(*emoji, "emoji/emoji-data.txt", "# Used with Emoji Version "+emojiVersion+" ", "Extended_Pictographic")
	if err != nil {
		log.Fatal(err)
	}
	spans = append(spans, pictographic...)
	sort.Slice(spans, func(i, j int) bool { return spans[i].lo < spans[j].lo })

	// Ranges that touch and share a property merge into one, and ranges
	// that overlap would give a code point two properties.
	var merged []span
	for _, s := range spans {
		if _, ok := props[s.prop]; !ok {
			log.Fatalf("unknown property %s at %04X", s.prop, s.lo)
		}
		if n := len(merged); n > 0 {
			last := &merged[n-1]
			if s.lo <= last.hi {
				log.Fatalf("%04X..%04X %s overlaps %04X..%04X %s", s.lo, s.hi, s.prop, last.lo, last.hi, last.prop)
			}
			if s.lo == last.hi+1 && s.prop == last.prop {
				last.hi = s.hi
				continue
			}
		}
		merged = append(merged, s)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/gengrapheme from GraphemeBreakProperty-%s.txt and emoji-data.txt %s. DO NOT EDIT.\n\n", unicodeVersion, emojiVersion)
	buf.WriteString("package regex\n\n")
	buf.WriteString("// graphemeUnicodeVersion is the Unicode version the table was generated\n")
	buf.WriteString("// from, that of the grapheme tables in jq 1.8.2's Oniguruma 6.9.10.\n")
	fmt.Fprintf(&buf, "const graphemeUnicodeVersion = %q\n\n", unicodeVersion)
	buf.WriteString("// graphemeRanges lists, in code point order, every range of code points\n")
	buf.WriteString("// whose grapheme cluster break property is not Other.\n")
	buf.WriteString("var graphemeRanges = [...]graphemeRange{\n")
	for _, s := range merged {
		fmt.Fprintf(&buf, "\t{0x%04X, 0x%04X, %s},\n", s.lo, s.hi, props[s.prop])
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o600); err != nil {
		log.Fatal(err)
	}
}

// read returns the ranges of the data file at path, or of the file at
// name under unicode.org's directory for unicodeVersion when path is
// empty, after checking that a line of its header starts with header. When
// only is not empty it keeps the ranges of that property alone.
func read(path, name, header, only string) ([]span, error) {
	src, err := open(path, name)
	if err != nil {
		return nil, err
	}
	defer func() { _ = src.Close() }()

	var spans []span
	versioned := false
	scan := bufio.NewScanner(src)
	for scan.Scan() {
		line := scan.Text()
		if strings.HasPrefix(line, header) {
			versioned = true
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		prop := strings.TrimSpace(fields[1])
		if only != "" && prop != only {
			continue
		}
		lo, hi, found := strings.Cut(strings.TrimSpace(fields[0]), "..")
		if !found {
			hi = lo
		}
		spans = append(spans, span{lo: code(lo), hi: code(hi), prop: prop})
	}
	if err := scan.Err(); err != nil {
		return nil, err
	}
	if !versioned {
		return nil, fmt.Errorf("%s has no header line starting %q", name, header)
	}
	return spans, nil
}

func open(path, name string) (io.ReadCloser, error) {
	if path != "" {
		return os.Open(path)
	}
	url := "https://www.unicode.org/Public/" + unicodeVersion + "/ucd/" + name
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, url, http.NoBody)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		_ = resp.Body.Close()
		return nil, fmt.Errorf("fetching %s: %s", url, resp.Status)
	}
	return resp.Body, nil
}

func code(s string) rune {
	v, err := strconv.ParseInt(strings.TrimSpace(s), 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(v)
}
