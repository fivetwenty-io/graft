//go:build ignore

// gen_fold writes fold.go, the table of full case foldings that the
// Oniguruma flavor applies under IgnoreCase. It reads the F entries of the
// Unicode CaseFolding.txt for the Unicode version of the Go toolchain that
// runs it, from the file named by -data or else from unicode.org.
//
//	go generate ./pkg/regex
//	go run gen_fold.go -data /path/to/CaseFolding.txt
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	data := flag.String("data", "", "path to CaseFolding.txt; downloaded from unicode.org when empty")
	out := flag.String("o", "fold.go", "output file")
	flag.Parse()

	src, err := open(*data)
	if err != nil {
		log.Fatal(err)
	}
	defer src.Close()

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen_fold.go from CaseFolding-%s.txt. DO NOT EDIT.\n\n", unicode.Version)
	buf.WriteString("package regex\n\n")
	buf.WriteString("// foldUnicodeVersion is the Unicode version the table was generated from.\n")
	fmt.Fprintf(&buf, "const foldUnicodeVersion = %q\n\n", unicode.Version)
	buf.WriteString("// fullFold is one F entry of CaseFolding.txt, a rune whose full case\n")
	buf.WriteString("// folding is more than one rune.\n")
	buf.WriteString("type fullFold struct {\n\tfrom rune\n\tto   []rune\n}\n\n")
	buf.WriteString("// fullFolds lists every F entry in rune order.\n")
	buf.WriteString("var fullFolds = []fullFold{\n")

	version := ""
	scan := bufio.NewScanner(src)
	for scan.Scan() {
		line := scan.Text()
		if strings.HasPrefix(line, "# CaseFolding-") {
			version = strings.TrimSuffix(strings.TrimPrefix(line, "# CaseFolding-"), ".txt")
		}
		fields := strings.Split(line, ";")
		if strings.HasPrefix(line, "#") || len(fields) < 3 || strings.TrimSpace(fields[1]) != "F" {
			continue
		}
		from := hex(fields[0])
		var to []string
		for _, cp := range strings.Fields(fields[2]) {
			to = append(to, fmt.Sprintf("0x%04X", hex(cp)))
		}
		name := ""
		if i := strings.Index(line, "#"); i >= 0 {
			name = " // " + strings.TrimSpace(line[i+1:])
		}
		fmt.Fprintf(&buf, "\t{0x%04X, []rune{%s}},%s\n", from, strings.Join(to, ", "), name)
	}
	if err := scan.Err(); err != nil {
		log.Fatal(err)
	}
	if version != unicode.Version {
		log.Fatalf("CaseFolding.txt is version %q, the toolchain's unicode package is %q", version, unicode.Version)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

func open(path string) (io.ReadCloser, error) {
	if path != "" {
		return os.Open(path)
	}
	url := "https://www.unicode.org/Public/" + unicode.Version + "/ucd/CaseFolding.txt"
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("fetching %s: %s", url, resp.Status)
	}
	return resp.Body, nil
}

func hex(s string) rune {
	v, err := strconv.ParseUint(strings.TrimSpace(s), 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(v)
}
